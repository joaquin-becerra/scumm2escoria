@dataclass
class Namer:
    """Numbers -> identifiers, with what the game's tables know."""
    version: int
    rooms: dict[int, str] = field(default_factory=dict)
    objects: dict[int, str] = field(default_factory=dict)    # number -> Room::name
    actors: set[int] = field(default_factory=set)
    verbs: dict[int, str] = field(default_factory=dict)
    scripts: dict[int, str] = field(default_factory=dict)    # number -> Room::name
    sounds: dict[int, str] = field(default_factory=dict)
    costumes: dict[int, str] = field(default_factory=dict)
    charsets: dict[int, str] = field(default_factory=dict)
    anims: dict[int, str] = field(default_factory=dict)      # costume frame -> constant
    aliases: dict[str, str] = field(default_factory=dict)    # g12 -> a name it deserves
    actor_params: dict[int, set[int]] = field(default_factory=dict)  # script -> actor params
    classes: dict[int, str] = field(default_factory=lambda: dict(ENGINE_CLASSES))
    globals_used: set[str] = field(default_factory=set)

    def var(self, name: str, locals_: dict[int, str]) -> str:
        kind, number = name[0], int(name[1:])
        if kind == "L":
            return locals_.get(number, f"l{number}")
        if kind == "T":
            return f"t{number}"
        if kind == "V":
            known = engine_vars(self.version).get(number)
            if known:
                return known
            ident = f"g{number}"
        else:
            ident = f"b{number}"
        ident = self.aliases.get(ident, ident)
        self.globals_used.add(ident)
        return ident

    def actor(self, number: int) -> str:
        return f"actor_{number}"

    def class_name(self, number: int) -> str:
        return self.classes.get(number, f"Class{number}")

    def typed(self, value: int, kind: str, room: Optional[str]) -> str:
        """A literal argument, as the identifier its kind says it is."""
        table = {"r": self.rooms, "v": self.verbs, "c": self.costumes, "s": self.sounds,
                 "H": self.charsets, "A": self.anims}.get(kind)
        if table is not None:
            return table.get(value, str(value))
        if kind == "a":
            return self.actor(value) if value in self.actors else str(value)
        if kind == "o":
            if value in self.actors:
                return self.actor(value)
            name = self.objects.get(value, str(value))
            # Objects of the same room go by their plain name, as in ScummC.
            return name.split("::")[1] if room and name.startswith(f"{room}::") else name
        if kind == "S":
            return self.script(value, room) or str(value)
        return str(value)

    def script(self, number: int, room: Optional[str]) -> Optional[str]:
        if number >= 200 and room:          # room-local numbers repeat between rooms
            return f"{room}::local_{number}"
        return self.scripts.get(number)


FORMATS = {"int": "i", "verb": "v", "name": "n", "string": "s"}


def scummc_text(text: str, namer: "Namer", locals_: dict[int, str]) -> str:
    """Message escapes as ScummC writes them: {name:267} -> %n{g267}."""
    def replace(match):
        code, value = FORMATS.get(match[1]), int(match[2])
        if code is None:
            return ""
        return f"%{code}{{{namer.var(var_name(value), locals_)}}}"
    # Pauses stay as ScummC's escapes, which quote() writes.
    text = text.replace("{wait}", "\x00wait").replace("{keep}", "\x00keep").replace("{unknown8}", "")
    return re.sub(r"\{(\w+):(\d+)\}", replace, text)


def quote(text: str) -> str:
    text = text.replace("\\", "\\\\").replace('"', '\\"')
    text = text.replace("\x00wait", "\\w").replace("\x00keep", "\\k").replace("\n", "\\n")
    return '"' + text + '"'


FOLDS = {"+": lambda a, b: a + b, "-": lambda a, b: a - b, "*": lambda a, b: a * b,
         "&": lambda a, b: a & b, "|": lambda a, b: a | b}


def fold(e):
    """Compute operations on constants: the compiler left `3 + 128` as it was written."""
    if isinstance(e, dict) and e.get("call") in FOLDS and len(e["args"]) == 2:
        left, right = fold(e["args"][0]), fold(e["args"][1])
        if isinstance(left, int) and isinstance(right, int):
            return FOLDS[e["call"]](left, right)
        return {"call": e["call"], "args": [left, right]}
    return e


def bare(text: str) -> str:
    """Drop parentheses around a whole expression."""
    while text.startswith("(") and text.endswith(")"):
        depth, quoted = 0, False
        for pos, c in enumerate(text):
            if c == '"' and text[pos - 1] != "\\":
                quoted = not quoted
            elif not quoted and c == "(":
                depth += 1
            elif not quoted and c == ")":
                depth -= 1
                if depth == 0 and pos < len(text) - 1:
                    return text
        text = text[1:-1]
    return text


class Writer:
    """Expressions and statements of one piece of code."""

    def __init__(self, namer: Namer, room: Optional[str], locals_: dict[int, str]):
        self.namer, self.room, self.locals = namer, room, locals_

    def expr(self, e, kind: str = "n") -> str:
        e = fold(e)
        if isinstance(e, bool) or isinstance(e, int):
            if kind == "C":
                return self.class_name(e)
            if kind == "K":     # setting classes: the high bit means "on"
                name = self.namer.class_name(e & 0x7F)
                return f"0x80 + {name}" if e & 0x80 else name
            return self.namer.typed(e, kind, self.room)
        if isinstance(e, list):
            return "[" + ", ".join(self.expr(x, kind if kind in "CK" else "n") for x in e) + "]"
        if "var" in e:
            name = self.namer.var(e["var"], self.locals)
            return f"{name}[{self.expr(e['index'])}]" if "index" in e else name
        if "text" in e:
            return quote(scummc_text(e["text"], self.namer, self.locals))
        return self.call(e["call"], e["args"])

    def class_name(self, value: int) -> str:
        name = self.namer.class_name(value & 0x7F)
        return name if value & 0x80 or not value else f"!{name}"

    def index(self, array: int, value) -> str:
        return self.expr(value, "a" if self.array(array) == "actorObject" else "n")

    def array(self, number: int) -> str:
        """Arrays are held in variables: the number is a variable's, locals included."""
        return self.namer.var(var_name(number), self.locals)

    def side_kinds(self, left, right) -> tuple[str, str]:
        """Comparing with vrb / objA / objB says what a literal on the other side is."""
        def kind(e):
            name = self.expr(e) if isinstance(e, dict) and "var" in e else ""
            return {"vrb": "v", "objA": "o", "objB": "o", "VAR_EGO": "a"}.get(name, "n")
        return kind(right), kind(left)

    def call(self, name: str, args: list) -> str:
        if name == "!":
            return f"!{self.expr(args[0])}"
        if name in OPERATORS:
            left_kind, right_kind = self.side_kinds(args[0], args[1])
            return f"({self.expr(args[0], left_kind)} {name} {self.expr(args[1], right_kind)})"
        if name == "arrayRead":
            return f"{self.array(args[0])}[{self.index(args[0], args[1])}]"
        if name == "arrayRead2":
            return f"{self.array(args[0])}[{self.expr(args[1])}, {self.expr(args[2])}]"
        target, kinds = FUNCTIONS.get(name, (name, ""))
        if name == "ifClassOfIs" and len(args[1]) == 1:
            return f"{self.expr(args[0], 'o')} is {self.expr(args[1][0], 'C')}"
        if name == "isAnyOf" and isinstance(args[0], dict):
            subject = self.expr(args[0])
            item = {"vrb": "v", "objA": "o", "objB": "o"}.get(subject, "n")
            values = ", ".join(self.expr(a, item) for a in args[1])
            return f"isAnyOf({subject}, [{values}])"
        parts = [bare(self.expr(a, kinds[i] if i < len(kinds) else "n")) for i, a in enumerate(args)]
        return f"{target}({', '.join(parts)})"

    def sub_call(self, table: dict, sub: dict) -> str:
        target, kinds = table.get(sub["call"], (sub["call"], ""))
        parts = [bare(self.expr(a, kinds[i] if i < len(kinds) else "n")) for i, a in enumerate(sub["args"])]
        return f"{target}({', '.join(parts)});"

    def script_args(self, number, args: list) -> str:
        actors = self.namer.actor_params.get(number, set()) if isinstance(number, int) else set()
        return ", ".join(bare(self.expr(a, "a" if k in actors else "n")) for k, a in enumerate(args))

    def script_call(self, number, args: list) -> str:
        arguments = self.script_args(number, args)
        name = self.namer.script(number, self.room) if isinstance(number, int) else None
        if name:
            return f"{name}({arguments});"
        # A script chosen at runtime: unknown parameters, but numbers are likely objects.
        values = ", ".join(bare(self.expr(a, "o")) for a in args)
        return f"startScript0({self.expr(number)}, [{values}]);"

    def statement(self, i) -> list[str]:
        name, args = i.name, i.args
        if name in SKIPPED or name == "pop":
            return []
        if name == "move":
            target = self.expr(i.result)
            kind = "S" if target.endswith("_SCRIPT") else "a" if target == "VAR_EGO" else "n"
            return [f"{target} = {bare(self.expr(args[0], kind))};"]
        if name in ("increment", "decrement"):
            return [f"{self.expr(i.result)}{'++' if name == 'increment' else '--'};"]
        if name == "arrayWrite":
            kind = "o" if self.array(args[0]) == "actorObject" else "n"
            return [f"{self.array(args[0])}[{self.index(args[0], args[1])}] = {self.expr(args[2], kind)};"]
        if name == "arrayWrite2":
            return [f"{self.array(args[0])}[{self.expr(args[1])}, "
                    f"{self.expr(args[2])}] = {self.expr(args[3])};"]
        if name == "arrayOps":
            array = self.array(args[0])
            sub = args[1]
            if sub["call"] == "assignString":
                return [f"{array}[{self.expr(sub['args'][0])}] = {self.expr(sub['args'][1])};"]
            return [f"{array}[{self.expr(sub['args'][1])}] = {self.expr(sub['args'][0])};"]
        if name in ("startScriptQuick", "startScriptQuick2"):
            return [self.script_call(args[0], args[1])]
        if name == "startScript":
            flags = fold(args[0])
            if flags == 0:
                return [self.script_call(args[1], args[2])]
            script = self.expr(args[1], "S")
            return [f"startScript({self.expr(flags)}, {script}, [{self.script_args(args[1], args[2])}]);"]
        if name == "chainScript":
            return [self.script_call(args[0], args[1]), "return;"]
        if name == "jumpToScript":
            return [self.script_call(args[1], args[2]), "return;"]
        if name == "talkActor":
            return [f"actorSay({self.expr(args[0], 'a')}, {self.expr(args[1])});"]
        if name == "talkEgo":
            return [f"egoSay({self.expr(args[0])});"]
        if name == "setObjectName":
            return [f"setObjectName({self.expr(args[0], 'o')}, {self.expr(args[1])});"]
        if name in SUB_FAMILIES:
            family = SUB_FAMILIES[name]
            subs = [a for a in args if isinstance(a, dict) and "call" in a]
            out = []
            if name in ("actorOps", "verbOps") and args and not isinstance(args[0], dict) \
                    or name in ("actorOps", "verbOps") and args and "var" in args[0]:
                out.append(self.sub_call(family, {"call": "setCurrent", "args": [args[0]]}))
            return out + [self.sub_call(family, s) for s in subs]
        if name == "wait":
            return [self.sub_call(WAITS, args[0])]
        if name == "systemOps":
            sub = args[0]["call"] if args and isinstance(args[0], dict) else {1: "restart", 2: "pause", 3: "quit"}[args[0]]
            return [f"{SYSTEM[sub]}();"]
        if name == "saveRestoreVerbs":
            sub = args[0]
            target = {"save": "saveVerbs", "restore": "restoreVerbs", "delete": "deleteVerbs"}[sub["call"]]
            return [f"{target}({', '.join(self.expr(a) for a in sub['args'])});"]
        if name == "printDefaults":
            keys = "".join(f"{s['call']}," for s in args[1:])
            place = [self.expr(a) for s in args[1:] for a in s["args"]]
            return [f"printDefaults({', '.join([quote(str(args[0])), quote(keys), *place])});"]
        if name in PRINTS:
            sub = args[0]
            if sub["call"] != "text":
                return []
            if name == "printEgo":
                return [f"egoSay({self.expr(sub['args'][0])});"]
            place = [self.expr(a) for s in args[1:] for a in s["args"]]
            keys = [quote("".join(f"{s['call']}," for s in args[1:]))] if len(args) > 1 else []
            return [f"{PRINTS[name]}({', '.join([self.expr(sub['args'][0]), *keys, *place])});"]
        return [self.call(name, args) + ";"]


class Structurer:
    """Rebuild if / while / switch / cutscene / try from a list of instructions."""

    def __init__(self, instrs: list, size: int, writer: Writer):
        self.ins, self.size, self.w = instrs, size, writer
        self.index = {}
        for n, i in enumerate(instrs):
            self.index.setdefault(i.offset, n)
        self.index[size] = len(instrs)
        self.gotos: set[int] = set()
        self.loops_done: set[int] = set()

    def at(self, offset: int) -> Optional[int]:
        return self.index.get(offset)

    def offset(self, n: int) -> int:
        return self.ins[n].offset if n < len(self.ins) else self.size

    def condition(self, i) -> str:
        return bare(self.w.expr(i.args[0]))

    def back_edge(self, n: int, hi: int) -> Optional[int]:
        """The last jump in n..hi going back to instruction n."""
        here = self.ins[n].offset
        found = None
        for j in range(n, hi):
            i = self.ins[j]
            if i.name in JUMPS and i.target == here:
                found = j
        return found

    def goto(self, target: int) -> str:
        self.gotos.add(target)
        return f"goto L{target:04x};"

    def block(self, lo: int, hi: int, loop=None, brk=None) -> list[str]:
        out: list[str] = []
        n = lo
        while n < hi:
            if self.ins[n].offset in self.gotos:
                out.append(f"L{self.ins[n].offset:04x}:")
            lines, n = self.step(n, hi, loop, brk)
            converted = self.as_for(out, lines)
            out += lines if converted is None else converted
        return out

    @staticmethod
    def as_for(before: list[str], lines: list[str]) -> Optional[list[str]]:
        """`i = 0; while(i < n) { ...; i++; }` was a for: the translator knows that form."""
        match = re.fullmatch(r"while\((\w+) ([<>=!]+) (.+)\) \{", lines[0]) if lines else None
        if match is None or len(lines) < 3 or not before:
            return None
        var = match[1]
        if lines[-2] not in (f"{var}++;", f"{var}--;") or not before[-1].startswith(f"{var} = "):
            return None
        init = before.pop().rstrip(";")
        return [f"for({init}; {var} {match[2]} {match[3]}; {lines[-2].rstrip(';')}) {{", *lines[1:-2], "}"]

    def step(self, n: int, hi: int, loop, brk) -> tuple[list[str], int]:
        i = self.ins[n]
        if n not in self.loops_done:
            last = self.back_edge(n, hi)
            if last is not None:
                self.loops_done.add(n)
                return self.loop(n, last), last + 1
        if i.name == "jumpRelative":
            if i.target == self.offset(n + 1):
                return [], n + 1
            if brk is not None and i.target == brk:
                return ["break;"], n + 1
            if loop is not None and i.target == loop[0]:
                return ["continue;"], n + 1
            return [self.goto(i.target)], n + 1
        if i.name in ("if", "ifNot"):
            return self.conditional(n, hi, loop, brk)
        if i.name == "cutscene":
            return self.cutscene(n, hi, loop, brk)
        if i.name == "beginOverride":
            return self.override(n, hi, loop, brk)
        if i.name == "stopObjectCode":
            return ([] if n == len(self.ins) - 1 else ["return;"]), n + 1
        if i.name in ("endCutscene", "endOverride"):
            return [], n + 1
        return self.w.statement(i), n + 1

    def loop(self, n: int, last: int) -> list[str]:
        first, end = self.ins[n], self.ins[last]
        head, exit_ = first.offset, self.offset(last + 1)
        body_loop = (head, exit_)
        if end.name == "jumpRelative":
            if first.name in ("if", "ifNot") and first.target == exit_:
                word = "while" if first.name == "ifNot" else "until"
                body = self.block(n + 1, last, body_loop, exit_)
                if len(body) == 1:
                    return [f"{word}({self.condition(first)}) {body[0]}"]
                return [f"{word}({self.condition(first)}) {{", *body, "}"]
            body = self.block(n, last, body_loop, exit_)
            return ["while(1) {", *body, "}"]
        word = "while" if end.name == "if" else "until"
        body = self.block(n, last, body_loop, exit_)
        return ["do {", *body, f"}} {word}({self.condition(end)});"]

    def case_test(self, n: int):
        """(subject, value) when instruction n opens a switch case."""
        i = self.ins[n]
        if i.name not in ("if", "ifNot") or n + 1 >= len(self.ins):
            return None
        cond = i.args[0]
        op = "!=" if i.name == "if" else "=="
        if not isinstance(cond, dict) or cond.get("call") != op:
            return None
        follow = self.ins[n + 1]
        if follow.name != "pop" or follow.args[0] != cond["args"][0]:
            return None
        return cond["args"][0], cond["args"][1]

    def switch(self, n: int, hi: int, loop) -> tuple[list[str], int]:
        subject = self.case_test(n)[0]
        cases, cur, end = [], n, None
        while cur < hi and self.case_test(cur) and self.case_test(cur)[0] == subject:
            value = self.case_test(cur)[1]
            nxt = self.at(self.ins[cur].target)
            stop, ends = nxt, False
            last = self.ins[nxt - 1] if nxt > 0 else None
            if last is not None and last.name == "jumpRelative" and last.target > last.offset:
                stop = nxt - 1
                # A jump into the next case's body is `case A: case B:`.
                shared = self.case_test(nxt) is not None and last.target == self.offset(nxt + 2)
                if not shared:
                    end, ends = self.at(last.target), True
            cases.append((value, cur + 2, stop, ends))
            cur = nxt
        if end is None:
            end = cur + 1
        brk = self.offset(end)
        kind = {"vrb": "v", "objA": "o", "objB": "o"}.get(self.w.expr(subject), "n")
        out = [f"switch({self.w.expr(subject)}) {{"]
        for value, lo, stop, ends in cases:
            out.append(f"case {self.w.expr(value, kind)}:")
            out += self.block(lo, stop, loop, brk)
            if ends:
                out.append("break;")
        if cur < len(self.ins) and self.ins[cur].name == "pop":
            cur += 1
        if cur < end:
            out.append("default:")
            out += self.block(cur, end, loop, brk)
        out.append("}")
        return out, end

    def conditional(self, n: int, hi: int, loop, brk) -> tuple[list[str], int]:
        i = self.ins[n]
        if self.case_test(n):
            return self.switch(n, hi, loop)
        word = "if" if i.name == "ifNot" else "unless"
        cond = self.condition(i)
        end = self.at(i.target)
        if end is not None and n < end <= hi:
            last = self.ins[end - 1] if end - 1 > n else None
            if last is not None and last.name == "jumpRelative" and last.target > last.offset:
                other = self.at(last.target)
                is_exit = brk is not None and last.target == brk
                if other is not None and end < other <= hi and not is_exit:
                    then = self.block(n + 1, end - 1, loop, brk)
                    orelse = self.block(end, other, loop, brk)
                    return [f"{word}({cond}) {{", *then, "} else {", *orelse, "}"], other
            then = self.block(n + 1, end, loop, brk)
            if len(then) == 1:
                return [f"{word}({cond}) {then[0]}"], end
            return [f"{word}({cond}) {{", *then, "}"], end
        negated = "unless" if word == "if" else "if"
        if brk is not None and i.target == brk:
            return [f"{negated}({cond}) break;"], n + 1
        if loop is not None and i.target == loop[0]:
            return [f"{negated}({cond}) continue;"], n + 1
        return [f"{negated}({cond}) {self.goto(i.target)}"], n + 1

    def matching(self, n: int, hi: int, opening: str, closing: str) -> Optional[int]:
        depth = 0
        for j in range(n, hi):
            if self.ins[j].name == opening:
                depth += 1
            elif self.ins[j].name == closing:
                depth -= 1
                if depth == 0:
                    return j
        return None

    def cutscene(self, n: int, hi: int, loop, brk) -> tuple[list[str], int]:
        end = self.matching(n, hi, "cutscene", "endCutscene")
        args = self.ins[n].args[0] if self.ins[n].args else []
        head = f"cutscene({self.w.expr(args[0])}) {{" if args else "cutscene {"
        if end is None:
            return [head, *self.block(n + 1, hi, loop, brk), "}"], hi
        return [head, *self.block(n + 1, end, loop, brk), "}"], end + 1

    def override(self, n: int, hi: int, loop, brk) -> tuple[list[str], int]:
        """beginOverride; jump T; body; T: ifNot(VAR_OVERRIDE) -> U; handler; U: endOverride"""
        jump = self.ins[n + 1] if n + 1 < hi else None
        if jump is None or jump.name != "jumpRelative":
            return [], n + 1
        test = self.at(jump.target)
        end = self.matching(n, hi, "beginOverride", "endOverride")
        if test is None or end is None or test > end:
            return [], n + 1
        body = self.block(n + 2, test, loop, brk)
        handler = self.block(test, end, loop, brk)
        return ["try {", *body, "} override {", *handler, "}"], end + 1


def used_locals(instrs: list) -> tuple[list[int], list[int]]:
    """Local variables read before being written (parameters), and all of them."""
    read_first: set[int] = set()
    written: set[int] = set()
    seen: set[int] = set()

    def visit(value):
        if isinstance(value, dict):
            if value.get("var", "").startswith("L"):
                number = int(value["var"][1:])
                seen.add(number)
                if number not in written:
                    read_first.add(number)
            for key in ("index", "args"):
                if key in value:
                    visit(value[key])
        elif isinstance(value, list):
            for item in value:
                visit(item)

    for i in instrs:
        # Writing into a local array assigns the local.
        if i.name in ("arrayOps", "arrayWrite", "dimArray") and var_name(i.args[0]).startswith("L"):
            number = int(var_name(i.args[0])[1:])
            seen.add(number)
            written.add(number)
        visit(i.args)
        if isinstance(i.result, dict) and i.result.get("var", "").startswith("L"):
            number = int(i.result["var"][1:])
            seen.add(number)
            written.add(number)
    return sorted(read_first), sorted(seen)


def temporaries(instrs: list) -> list[str]:
    names = {i.result["var"] for i in instrs
             if isinstance(i.result, dict) and i.result.get("var", "").startswith("T")}
    return sorted(f"t{n[1:]}" for n in names)


def script_text(instrs: list, size: int, namer: Namer, room: Optional[str],
                names: Optional[dict[int, str]] = None) -> tuple[str, list[str]]:
    """Source of a script and its parameter names."""
    read_first, seen = used_locals(instrs)
    locals_ = dict(names or {})
    params = [locals_.get(n, f"l{n}") for n in range(max(read_first) + 1)] if read_first else []
    writer = Writer(namer, room, locals_)
    s = Structurer(instrs, size, writer)
    s.block(0, len(instrs))           # finds the goto targets...
    s.loops_done.clear()
    body = s.block(0, len(instrs))    # ...so labels come out on this pass
    others = [locals_.get(n, f"l{n}") for n in seen if locals_.get(n, f"l{n}") not in params]
    others += temporaries(instrs)
    head = [f"int {', '.join(others)};"] if others else []
    return "\n".join(head + body), params


def flat_blocks(instrs: list, size: int, namer: Namer, room: str) -> list[dict]:
    """A script as blocks of statements and the jumps between them. An override's own
    jump only happens when the player skips, and nothing here can be skipped that way."""
    writer = Writer(namer, room, {})
    s = Structurer(instrs, size, writer)
    targets = {i.target for i in instrs if i.target is not None}
    blocks: list[dict] = []
    current: Optional[dict] = None
    overriding = False
    for i in instrs:
        if current is None or i.offset in targets:
            if current is not None:
                current["next"] = i.offset
            current = {"offset": i.offset, "lines": [], "next": None}
            blocks.append(current)
        if i.name == "beginOverride":
            overriding = True
        elif i.name == "jumpRelative" and overriding:
            overriding = False
        elif i.name == "jumpRelative":
            current["next"] = i.target
            current = None
        elif i.name in ("if", "ifNot"):
            following = s.offset(s.at(i.offset) + 1)
            current.update(cond=s.condition(i), target=i.target, negate=i.name == "ifNot", next=following)
            current = None
        elif i.name == "stopObjectCode":
            current = None
        elif i.name not in ("endOverride", "cutscene", "endCutscene"):
            current["lines"] += writer.statement(i)
    return blocks


def verb_text(instrs: list, size: int, entries: dict[int, int], namer: Namer, room: str) -> str:
    """Body of an object's verb(): a case per handler, in code order."""
    locals_ = {0: "vrb", 1: "objA", 2: "objB"}
    writer = Writer(namer, room, locals_)
    s = Structurer(instrs, size, writer)
    starts = sorted(set(entries.values()))
    bounds = {}
    for k, offset in enumerate(starts):
        lo = s.at(offset)
        if lo is not None:
            bounds[offset] = (lo, s.at(starts[k + 1]) if k + 1 < len(starts) else len(instrs))

    def render() -> list[str]:
        lines = []
        for offset in starts:
            if offset not in bounds:
                continue
            for verb, entry in entries.items():
                if entry == offset:
                    lines.append("default:" if verb == 255 else f"case {namer.verbs.get(verb, verb)}:")
            lines += s.block(*bounds[offset])
        return lines

    render()
    s.loops_done.clear()
    lines = render()
    _, seen = used_locals(instrs)
    others = [f"l{n}" for n in seen if n > 2] + temporaries(instrs)
    head = [f"int {', '.join(others)};"] if others else []
    return "\n".join(head + lines)
