    def write_ui(self) -> None:
        S = self.SCALE
        verbs = self.game.verbs
        self._palette = self.verb_palette()
        bar = next((v for v in verbs if v.image and v.pos), None)
        top = bar.pos[1] if bar else 144
        panel_size = (320 * S, (200 - top) * S)
        # Some verbs share a place and take turns: the one showing at the start stays.
        place = {}
        on_screen = [v for v in verbs if v.is_button and v.pos[1] < SCREEN_HEIGHT]
        for v in sorted(on_screen, key=lambda v: not v.on):
            place.setdefault(v.pos, v)
        buttons = [v for v in on_screen if place[v.pos] is v]
        sentence = next((v for v in verbs if v.pos and v.label and "%" in v.label), None)
        slots = sorted((v for v in verbs if v.on and v.pos and not v.label and not v.image),
                       key=lambda v: (v.pos[1], v.pos[0]))
        # Inventory arrows are symbols; other lines with words belong to scenes.
        arrows = [v for v in verbs if v.pos and v.label and not v.is_button and "%" not in v.label
                  and not any(c.isalpha() for c in v.label)]
        verb_font = self.fonts.get(buttons[0].charset) if buttons and buttons[0].charset else None

        self.write_verbs_menu(buttons, top, verb_font)
        self.write_inventory_ui(slots, arrows, top, verb_font)
        self.write_sentence_script(buttons)

        scn = Resource("gd_scene")
        scn.node("game", "Node2D", props={
            "script": scn.ext("Script", f"{ADDON}/game.gd"),
            "main_menu": Raw('NodePath("ui/main_menu")'),
            "pause_menu": Raw('NodePath("ui/pause_menu")'),
            "ui_parent_control_node": Raw('NodePath("ui/Control")'),
        })
        scn.node("dialog_layer", "CanvasLayer", ".")
        dialog = {"layout_mode": 3, "script": scn.ext("Script", f"{CORE}/game/scenes/dialogs/esc_dialog_player.gd")}
        if self.theme_path("text"):
            dialog["theme"] = scn.ext("Theme", self.theme_path("text"))
        scn.node("ESCDialogPlayer", "Control", "dialog_layer", dialog)

        scn.node("ui", "CanvasLayer", ".")
        scn.node("Control", "Control", "ui", {
            "layout_mode": 3, "anchors_preset": 15, "anchor_right": 1.0, "anchor_bottom": 1.0,
            "mouse_filter": 2,
        })
        base = "ui/Control/panel_down"
        scn.node("panel_down", "Control", "ui/Control", {
            "layout_mode": 0,
            "offset_top": top * S, "offset_right": panel_size[0], "offset_bottom": top * S + panel_size[1],
        })
        if bar:
            obj = self.game.objects[bar.image]
            img = Image.open(obj.states[0].image).convert("RGBA")
            tex = scn.ext("Texture2D", self.save_png(img, "res://ui/verb_bar.png"))
            scn.node("background", "TextureRect", base, {
                "layout_mode": 0,
                "offset_left": (bar.pos[0]) * S, "offset_top": (bar.pos[1] - top) * S,
                "offset_right": (bar.pos[0] + img.width) * S, "offset_bottom": (bar.pos[1] - top + img.height) * S,
                "texture": tex, "mouse_filter": 2,
            })
        # The node names below are the paths the 9-verbs game.gd looks up.
        full = {"layout_mode": 0, "offset_right": panel_size[0], "offset_bottom": panel_size[1], "mouse_filter": 2}
        scn.node("VBoxContainer", "Control", base, full)
        scn.node("MarginContainer", "Control", f"{base}/VBoxContainer", full)
        tip = {"layout_mode": 0, "offset_right": panel_size[0], "mouse_filter": 2,
               "script": scn.ext("Script", "res://ui/sentence_line.gd"),
               "bbcode_enabled": True, "scroll_active": False, "text": ""}
        if sentence:
            line_h = 12
            tip.update({"offset_top": (sentence.pos[1] - top) * S,
                        "offset_bottom": (sentence.pos[1] - top + line_h) * S})
            col = self.pal(sentence.color)
            if col:
                tip["color"] = _color(col)
        if verb_font:
            tip["theme_override_fonts/normal_font"] = scn.ext("FontFile", verb_font)
            tip["theme_override_font_sizes/normal_font_size"] = self.font_sizes[verb_font]
        scn.node("tooltip", "RichTextLabel", f"{base}/VBoxContainer/MarginContainer", tip)
        scn.node("HBoxContainer", "Control", f"{base}/VBoxContainer", full)
