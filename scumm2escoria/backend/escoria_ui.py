def _decode(label: str) -> str:
    """ScummC string escapes such as \\x03 (the verb font's arrow glyphs)."""
    return codecs.decode(label, "unicode_escape") if "\\" in label else label


def _color(rgb) -> Raw:
    return Raw("Color(%.4f, %.4f, %.4f, 1)" % rgb)


